def make_claude_prompt(user_input, context=None, base_loaded=False):
    if base_loaded and context:
        # База загружена: всегда использовать её для подбора, но разрешено отвечать на общее
        return (
            "Ты — профессиональный парфюмерный консультант. Ранее пользователь запросил подбор аромата, ты получил базу в формате JSON. "
            "Теперь, если пользователь просит подобрать аромат, ты обязан использовать **только эту базу** и не придумывать ароматы. "
            "Если пользователь задаёт общий вопрос (например, о стойкости, нотах, истории парфюмерии) — можешь использовать свои знания.\n\n"
            f"База ароматов: {context}\n\n"
            f"Запрос пользователя: {user_input}"
        )
    else:
        # Первая фаза: Claude сам решает, вопрос это или подбор
        return (
            "Ты — профессиональный парфюмерный консультант магазина Золотое Яблоко. "
            "Если пользователь задаёт общий вопрос (например, про парфюмерные ноты, стойкость, группы ароматов) — ответь на него из своих знаний.\n"
            "Если пользователь просит подобрать аромат — **не подбирай**. Вместо этого просто напиши точно: `ЗАГРУЖАЮ БАЗУ АРОМАТОВ`. "
            "Без дополнительных пояснений, только эта фраза. После этого тебе пришлют базу и ты сможешь подобрать аромат.\n\n"
            f"Запрос пользователя: {user_input}"
        )
